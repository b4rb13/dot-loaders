import { rm, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import * as wrapper from 'dotquilt/wrapper';
import { writeWrapperStyles } from './wrapper-css.js';

const cwd = resolve(import.meta.dir, '../packages/angular');

// Angular puts a component's `styles` in the document head once, with the
// app's CSP nonce. Its compiler needs them as string literals, so they are
// written out from dotquilt/wrapper on every build (and git-ignored).
const css = (...parts: (readonly string[])[]) =>
  JSON.stringify(parts.flat().join('\n'));
await writeFile(
  resolve(cwd, 'src/styles.generated.ts'),
  `// Generated by scripts/build-angular.ts from dotquilt/wrapper. Don't edit.
export const skeletonBlockCss = ${css(wrapper.wrapperSkeletonStyles(), wrapper.wrapperSkeletonMarkStyles())};
export const skeletonLineCss = ${css(wrapper.wrapperLineStyles(), wrapper.wrapperLineMarkStyles())};
export const skeletonCircleCss = ${css(wrapper.wrapperCircleStyles(), wrapper.wrapperCircleMarkStyles())};
export const skeletonTextCss = ${css(wrapper.wrapperSkeletonTextStyles(), wrapper.wrapperSkeletonTextMarkStyles())};
export const typingCss = ${css(wrapper.wrapperTypingStyles(), wrapper.wrapperTypingMarkStyles())};
export const textCss = ${css(wrapper.wrapperTextStyles, wrapper.wrapperTextMarkStyles)};
export const chartCss = ${css(wrapper.wrapperChartStyles, wrapper.wrapperChartMarkStyles)};
export const tableCss = ${css(wrapper.wrapperTableStyles)};
export const regionCss = ${css(wrapper.wrapperRegionStyles)};
`,
);

await rm(resolve(cwd, 'dist'), { recursive: true, force: true });
// ng-packagr compiles in Angular's partial mode, which every app's Angular
// links. Bun runs it: Angular 22's tools check for a newer Node than some
// machines have, and Bun reports a compatible one.
const packager = Bun.spawn(
  [
    'bun',
    '--bun',
    'x',
    '--no-install',
    'ng-packagr',
    '-p',
    'ng-package.json',
    '-c',
    'tsconfig.lib.json',
  ],
  { cwd, stdout: 'inherit', stderr: 'inherit' },
);
if (await packager.exited) throw new Error('Angular build failed');
// ng-packagr writes a package.json of its own; the package root's is the one
// published, pointing into dist.
await rm(resolve(cwd, 'dist/package.json'), { force: true });
await writeWrapperStyles(resolve(cwd, 'dist'));
